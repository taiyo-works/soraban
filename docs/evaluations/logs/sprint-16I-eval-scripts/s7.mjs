import { launch, signedCtx, SHOT } from "./lib.mjs";
const AC = "9c29615d-b3d2-415c-8d29-2e990530bc19";
const b = await launch();
const ctx = await signedCtx(b, "a-manager", { viewport: { width: 375, height: 812 }, hasTouch: true });
const page = await ctx.newPage();
await page.clock.setFixedTime(new Date("2027-01-05T12:00:00+09:00"));
await page.goto(`/ops/inspections/new?aircraftId=${AC}`);
await page.getByRole("form", { name: "日常点検の入力" }).waitFor();
await page.getByRole("radiogroup", { name: "機体全般の結果" }).getByRole("radio", { name: "正常" }).check();
await page.getByRole("radiogroup", { name: "プロペラの結果" }).getByRole("radio", { name: "異常" }).check();
await page.getByLabel("プロペラの備考").fill("欠け");
await page.addStyleTag({ content: "html{filter:grayscale(1) !important}" });
await page.waitForTimeout(500);
await page.locator('[data-testid="inspection-group-body"]').scrollIntoViewIfNeeded();
await page.getByTestId("inspection-group-note").scrollIntoViewIfNeeded();
await page.evaluate(() => window.scrollBy(0, -80));
await page.waitForTimeout(300);
await page.screenshot({ path: `${SHOT}/s7-gray-form-375.png` });
await page.goto("/ops/inspections?includeVoided=1");
await page.getByTestId("inspection-list").waitFor();
await page.addStyleTag({ content: "html{filter:grayscale(1) !important}" });
await page.waitForTimeout(500);
await page.screenshot({ path: `${SHOT}/s7-gray-list-375.png`, fullPage: true });
await b.close();
